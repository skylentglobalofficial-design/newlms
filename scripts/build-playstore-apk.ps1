                        "} catch(e){}" +
                        "window.location.replace('" + targetUrl.replace("'", "") + "');" +
                        "})();";
                    webView.evaluateJavascript(js, null);
                } else {
                    webView.loadUrl(targetUrl);
                }
            });
        }
    }
}
