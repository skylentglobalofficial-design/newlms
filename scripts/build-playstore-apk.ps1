# =============================================================================
# SKYLENT PLAY STORE NATIVE APK & AAB BUILDER (V39 Pure-ASCII PowerShell Safe)
# =============================================================================
$ErrorActionPreference = "Stop"

Write-Host ""
Write-Host "============================================================" -ForegroundColor Cyan
Write-Host "  SKYLENT PLAY STORE NATIVE APK / AAB BUILDER (v39)" -ForegroundColor Cyan
Write-Host "============================================================" -ForegroundColor Cyan

# Step 1: Security Audit - Ensure no server secrets are prefixed with VITE_
Write-Host "`n[1/5] Running Client Bundle Security Audit..." -ForegroundColor Yellow
if (Test-Path ".env") {
  $envLines = Get-Content ".env"
  foreach ($line in $envLines) {
    if ($line -match "^VITE_.*(SECRET|PASSWORD|DATABASE_URL|PRIVATE_KEY)") {
      throw "SECURITY BLOCK: Found sensitive server key in VITE_ variable: $line"
    }
  }
}
Write-Host "  [OK] Zero backend secrets exposed to client APK bundle." -ForegroundColor Green

# Step 2: Build Production Frontend Bundle (dist/)
Write-Host "`n[2/5] Building Standalone Frontend Bundle (dist/)..." -ForegroundColor Yellow
cmd /c "npx vite build"
if (-not (Test-Path "dist/index.html")) {
  throw "dist/index.html was not generated by vite build."
}
Write-Host "  [OK] Standalone UI bundle compiled into dist/." -ForegroundColor Green

# Step 3: Ensure Capacitor Android packages are installed
Write-Host "`n[3/5] Checking Capacitor Native Android Dependencies..." -ForegroundColor Yellow
if (-not (Test-Path "node_modules/@capacitor/android")) {
  Write-Host "  Installing @capacitor/core, @capacitor/cli, @capacitor/android..." -ForegroundColor Cyan
  cmd /c "npm install @capacitor/core @capacitor/android --no-Save"
  cmd /c "npm install -D @capacitor/cli --no-Save"
}
Write-Host "  [OK] Capacitor Android packages ready." -ForegroundColor Green

# Step 4: Initialize or Sync Android Native Project
Write-Host "`n[4/5] Syncing Bundled Assets into Native Android Project..." -ForegroundColor Yellow
if (-not (Test-Path "android")) {
  cmd /c "npx cap add android"
}
cmd /c "npx cap sync android"

$manifestPath = "android/app/src/main/AndroidManifest.xml"
if (Test-Path $manifestPath) {
  $manifest = Get-Content $manifestPath -Raw
  if ($manifest -notmatch "usesCleartextTraffic") {
    $replacement = '<application android:usesCleartextTraffic="false" android:allowBackup="false"'
    $manifest = $manifest.Replace("<application", $replacement)
    Set-Content -Path $manifestPath -Value $manifest -Encoding UTF8
    Write-Host "  [OK] Hardened AndroidManifest.xml (usesCleartextTraffic=false, allowBackup=false)." -ForegroundColor Green
  }
}

# Step 5: Build APK via Gradle if JAVA_HOME / Android SDK is present, else open/guide
Write-Host "`n[5/5] Checking Local Gradle / Android Studio Build..." -ForegroundColor Yellow
if (Test-Path "android/gradlew.bat") {
  Push-Location "android"
  cmd /c "gradlew.bat assembleDebug"
  $gradleExit = $LASTEXITCODE
  Pop-Location

  $apkFile = "android/app/build/outputs/apk/debug/app-debug.apk"
  if (($gradleExit -eq 0) -and (Test-Path $apkFile)) {
    $resolvedApk = (Resolve-Path $apkFile).Path
    Write-Host ""
    Write-Host "============================================================" -ForegroundColor Green
    Write-Host "  [SUCCESS] NATIVE ANDROID APK GENERATED!" -ForegroundColor Green
    Write-Host "  APK Path: $resolvedApk" -ForegroundColor White
    Write-Host "  Play Store Signed AAB: Run 'npx cap open android' -> Build -> Generate Signed Bundle / APK" -ForegroundColor Cyan
    Write-Host "============================================================" -ForegroundColor Green
  } else {
    Write-Host ""
    Write-Host "============================================================" -ForegroundColor Cyan
    Write-Host "  [READY] Native Android Project created at: .\android" -ForegroundColor Green
    Write-Host "  To compile the APK/AAB on Windows:" -ForegroundColor Yellow
    Write-Host "  1. Install Android Studio (includes Java JDK 17 + Android SDK)" -ForegroundColor White
    Write-Host "  2. Run: npx cap open android" -ForegroundColor White
    Write-Host "  3. In Android Studio: Build -> Build Bundle(s) / APK(s) -> Build APK(s)" -ForegroundColor White
    Write-Host "============================================================" -ForegroundColor Cyan
  }
}
