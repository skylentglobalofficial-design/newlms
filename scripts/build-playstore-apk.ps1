                            }
                            if (webView.canGoBack()) {
                                webView.goBack();
                                return;
                            }
                            long now = System.currentTimeMillis();
                            if (now - lastBackPressTime < 2000) {
                                finish();
                            } else {
                                lastBackPressTime = now;
                                Toast.makeText(MainActivity.this, "Press back again to exit Skylent", Toast.LENGTH_SHORT).show();
                            }
                        }
                    );
                } else {
