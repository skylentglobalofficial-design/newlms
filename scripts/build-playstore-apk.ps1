# =============================================================================
# SKYLENT PLAY STORE NATIVE APK & AAB BUILDER (V38 Security-Hardened)
# =============================================================================
# Usage:
#   .\scripts\build-playstore-apk.ps1
#
# What this script does:
# 1. Security Audit: Verifies zero backend secrets (DATABASE_URL, JWT_SECRET,
#    GOOGLE_CLIENT_SECRET, RAZORPAY_KEY_SECRET) are exposed in VITE_* env vars.
# 2. Compiles the standalone React/Vite frontend bundle into `dist/` so the APK
#    runs 100% locally as a real native application (NOT a website wrapper).
# 3. Installs & syncs Capacitor Android (`@capacitor/core`, `@capacitor/cli`,
#    `@capacitor/android`) into `android/`.
# 4. Hardens `android/app/src/main/AndroidManifest.xml` (`usesCleartextTraffic="false"`,
#    `allowBackup="false"`).
# 5. Builds the Debug APK (`app-debug.apk`) for instant phone testing or opens
#    Android Studio to generate the signed Play Store `.aab` bundle.
# =============================================================================

$ErrorActionPreference = "Stop"
Write-Host "`n============================================================" -ForegroundColor Cyan
Write-Host "  SKYLENT PLAY STORE NATIVE APK / AAB BUILDER (v38)" -ForegroundColor Cyan
Write-Host "============================================================`n" -ForegroundColor Cyan

# Step 1: Security Audit - Ensure no server secrets are prefixed with VITE_
Write-Host "[1/5] Running Client Bundle Security Audit..." -ForegroundColor Yellow
if (Test-Path ".env") {
  $envLines = Get-Content ".env"
  foreach ($line in $envLines) {
    if ($line -match "^VITE_.*(SECRET|PASSWORD|DATABASE_URL|PRIVATE_KEY)") {
      throw "SECURITY BLOCK: Found sensitive server key in VITE_ variable: $line"
    }
  }
}
Write-Host "  ✓ Zero backend secrets exposed to client APK bundle." -ForegroundColor Green

# Step 2: Build Production Frontend Bundle (`dist/`)
Write-Host "`n[2/5] Building Standalone Frontend Bundle (dist/)..." -ForegroundColor Yellow
npx vite build
if (-not (Test-Path "dist/index.html")) {
  throw "dist/index.html was not generated by vite build."
}
Write-Host "  ✓ Standalone UI bundle compiled into dist/." -ForegroundColor Green

# Step 3: Ensure Capacitor Android packages are installed
Write-Host "`n[3/5] Checking Capacitor Native Android Dependencies..." -ForegroundColor Yellow
if (-not (Test-Path "node_modules/@capacitor/android")) {
  Write-Host "  Installing @capacitor/core, @capacitor/cli, @capacitor/android..." -ForegroundColor Cyan
  npm install @capacitor/core @capacitor/android
  npm install -D @capacitor/cli
}
Write-Host "  ✓ Capacitor Android packages ready." -ForegroundColor Green

# Step 4: Initialize or Sync Android Native Project
Write-Host "`n[4/5] Syncing Bundled Assets into Native Android Project..." -ForegroundColor Yellow
if (-not (Test-Path "android")) {
  npx cap add android
}
npx cap sync android

# Harden AndroidManifest.xml against cleartext traffic and adb backup extraction
$manifestPath = "android/app/src/main/AndroidManifest.xml"
if (Test-Path $manifestPath) {
  $manifest = Get-Content $manifestPath -Raw
  if ($manifest -notmatch "usesCleartextTraffic") {
    $manifest = $manifest -replace "<application", '<application android:usesCleartextTraffic="false" android:allowBackup="false"'
    Set-Content -Path $manifestPath -Value $manifest -Encoding UTF8
    Write-Host "  ✓ Hardened AndroidManifest.xml (usesCleartextTraffic=false, allowBackup=false)." -ForegroundColor Green
  }
}

# Step 5: Build APK via Gradle if JAVA_HOME / Android SDK is present, else guide user
Write-Host "`n[5/5] Checking Local Gradle / Android Studio Build..." -ForegroundColor Yellow
if (Test-Path "android/gradlew.bat") {
  try {
    Push-Location "android"
    .\gradlew.bat assembleDebug
    Pop-Location
    $apkFile = "android/app/build/outputs/apk/debug/app-debug.apk"
    if (Test-Path $apkFile) {
      Write-Host "`n============================================================" -ForegroundColor Green
      Write-Host "  SUCCESS! NATIVE ANDROID APK GENERATED:" -ForegroundColor Green
      Write-Host "  Path: $((Resolve-Path $apkFile).Path)" -ForegroundColor White
      Write-Host "  For Play Store Signed .AAB: Run 'npx cap open android' -> Build -> Generate Signed Bundle / APK" -ForegroundColor Cyan
      Write-Host "============================================================`n" -ForegroundColor Green
    }
  } catch {
    Pop-Location
    Write-Host "`n  ℹ️ Android project is synced at .\android!" -ForegroundColor Cyan
    Write-Host "  Run 'npx cap open android' in Android Studio -> Build -> Generate Signed Bundle / APK (.aab / .apk)." -ForegroundColor White
  }
}
